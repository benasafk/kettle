import { build } from 'esbuild';
import { existsSync } from 'node:fs';
import { mkdir, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repository = fileURLToPath(new URL('../', import.meta.url));

/** No fixture or fallback component is emitted by this build. */
export async function buildPanel(root = repository) {
  const entry = resolve(root, 'apps/panel/bridge.ts');
  const component = resolve(root, 'apps/panel/project-review.ts');
  const resource = resolve(root, 'apps/worker/project-review-resource.ts');
  const output = resolve(root, 'apps/panel/generated/project-review-bundle.ts');
  // Remove stale output even when a subsequent build fails.
  await rm(output, { force: true });
  if (!existsSync(entry) && !existsSync(resource)) {
    return { status: 'not-integrated' };
  }
  if (!existsSync(entry) || !existsSync(component)) {
    throw new Error('Panel integration requires apps/panel/bridge.ts and apps/panel/project-review.ts. No stub will be built.');
  }
  const result = await build({
    absWorkingDir: root,
    entryPoints: [entry],
    outfile: 'project-review.js',
    bundle: true,
    platform: 'browser',
    format: 'iife',
    target: 'es2022',
    write: false,
    metafile: true,
    minify: true,
    sourcemap: false,
    legalComments: 'inline',
    // Preserve esbuild's default escaping for code embedded in inline scripts.
    supported: { 'inline-script': true },
    logLevel: 'silent',
  });
  if (result.outputFiles.length !== 1 || !result.outputFiles[0].path.endsWith('.js')) {
    throw new Error('Panel must be one self-contained script. Inline styles/assets; do not emit separate CSS or asset files.');
  }
  if (Object.values(result.metafile.outputs).some(value => value.imports.some(item => item.external))) {
    throw new Error('Panel bundle must not retain external imports.');
  }
  const componentInput = Object.keys(result.metafile.inputs).some(path => resolve(root, path) === component);
  if (!componentInput) throw new Error('Bridge must import the real project-review component.');
  const source = `// Generated by scripts/build-panel.mjs; do not edit or commit.\nexport const projectReviewScript: string = ${JSON.stringify(result.outputFiles[0].text)};\n`;
  await mkdir(dirname(output), { recursive: true });
  const temporary = `${output}.${process.pid}.tmp`;
  try {
    await writeFile(temporary, source);
    await rename(temporary, output);
  } finally {
    await rm(temporary, { force: true });
  }
  return { status: 'built', bytes: result.outputFiles[0].contents.length };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await buildPanel();
  console.log(result.status === 'built'
    ? `Panel browser bundle: ${result.bytes} bytes.`
    : 'Panel integration not present; no browser artifact emitted.');
}
